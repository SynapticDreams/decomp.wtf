#!/usr/bin/env python3
"""Build this Game Boy project and check the result against your own copy of the game, byte for byte.

    python build.py                  disassemble your copy, build, compare
    python build.py --fix-checksums  the same, then let rgbfix write the header's checksums (after you change it)

The game is assembly (RGBDS). Your copy, baserom.gb or baserom.gbc, is disassembled with mgbdis into
build/disassembly/ on every build, with the project's names (baserom.sym, which mgbdis reads next to the ROM) and
its notes as comments (comments.txt); RGBDS rebuilds it. Edit the names and comments there; the disassembly itself
is made from your copy and stays out of git. Generated by decomp.wtf (https://decomp.wtf).
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
OUT = ROOT / "build"
LABEL = re.compile(r"^([A-Za-z_][\w@#$]*)::?\s*$")


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def tools() -> tuple[Path, Path]:
    """(mgbdis.py, the folder with rgbasm/rgblink/rgbfix): decomp.wtf's pinned ones when it's installed, else
    MGBDIS (the path of mgbdis.py) and RGBDS on PATH."""
    try:
        from decompnet import toolchains

        mgbdis = next(iter(toolchains.path("mgbdis").glob("*/mgbdis.py")), None)
        rgbds = toolchains.path("rgbds")
        if mgbdis and (rgbds / "rgbasm").exists():
            return mgbdis, rgbds
    except ImportError:
        pass
    mgbdis = os.environ.get("MGBDIS")
    rgbasm = shutil.which("rgbasm")
    if not (mgbdis and Path(mgbdis).is_file() and rgbasm):
        fail("needs mgbdis and RGBDS: install decomp.wtf (it pins both), or put RGBDS on PATH and set MGBDIS to "
             "mgbdis.py's path")
    return Path(mgbdis), Path(rgbasm).parent


def run(argv: list, cwd: Path) -> None:
    proc = subprocess.run([str(a) for a in argv], cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace")
    if proc.returncode != 0:
        fail(f"{Path(str(argv[0])).name} failed:\n{(proc.stdout + proc.stderr).strip()[-2000:]}")


def comments() -> dict[str, list[str]]:
    """label -> its comment lines, from comments.txt (`Label: text`, one line each)."""
    out: dict[str, list[str]] = {}
    path = ROOT / "comments.txt"
    for line in path.read_text(encoding="utf-8").splitlines() if path.exists() else []:
        label, sep, text = line.partition(": ")
        if sep and LABEL.match(label + ":"):
            out.setdefault(label, []).append(text)
    return out


def annotate(folder: Path, notes: dict[str, list[str]]) -> int:
    """Put each label's comments above it in the disassembly; returns how many labels got some."""
    done = 0
    for f in sorted(folder.glob("bank_*.asm")):
        lines, out = f.read_text(encoding="utf-8").splitlines(), []
        for line in lines:
            m = LABEL.match(line)
            if m and m.group(1) in notes:
                out += [f"; {text}" for text in notes[m.group(1)]]
                done += 1
            out.append(line)
        f.write_text("\n".join(out) + "\n", encoding="utf-8")
    return done


def main(argv: list[str]) -> int:
    image = ROOT / B["image"]
    if not image.exists():
        fail(f"put your own copy of the game here as {B['image']}")
    if hashlib.sha1(image.read_bytes()).hexdigest() != B["sha1"]:
        fail(f"{B['image']} isn't the version this project is for (its sha1 differs)")
    mgbdis, rgbds = tools()
    disassembly = OUT / "disassembly"
    shutil.rmtree(disassembly, ignore_errors=True)
    OUT.mkdir(exist_ok=True)
    print("disassembling your copy with mgbdis (with the project's names)")
    run([sys.executable, mgbdis, image, "--output-dir", disassembly, "--overwrite"], ROOT)
    print(f"comments on {annotate(disassembly, comments())} labels")
    rom = f"game{image.suffix}"
    run([rgbds / "rgbasm", "-o", "game.o", "game.asm"], disassembly)
    run([rgbds / "rgblink", "-n", "game.sym", "-m", "game.map", "-o", rom, "game.o"], disassembly)
    # the header's checksums are in the disassembly as the original has them; rgbfix -v writes new ones
    run([rgbds / "rgbfix", *(["-v"] if "--fix-checksums" in argv else []), "-p", "255", rom], disassembly)
    built, original = (disassembly / rom).read_bytes(), image.read_bytes()
    shutil.copyfile(disassembly / rom, OUT / rom)
    if built == original:
        print(f"identical: build/{rom} is your copy of the game, byte for byte")
        return 0
    at = next((i for i, (a, b) in enumerate(zip(built, original)) if a != b), min(len(built), len(original)))
    print(f"differs: build/{rom} first differs from your copy at ${at:06x} ({len(built)} vs {len(original)} bytes)")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
